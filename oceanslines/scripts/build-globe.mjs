/**
 * Pre-computes the hero globe as static SVG paths, so the site ships no map
 * data or projection code. Re-run after changing the view or the ports:
 *
 *   node scripts/build-globe.mjs
 *
 * Writes public/globe-base.svg (the static map) and
 * src/components/landing/globe-geometry.ts (routes and points).
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoGraticule10, geoInterpolate, geoOrthographic, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topology = require("world-atlas/land-110m.json");

const R = 230;
const CX = 260;
const CY = 260;
const ROTATION = [38, -26]; // centred over the North Atlantic
const ARC_HEIGHT = 0.14;
const SAMPLES = 64;

const PORTS = {
  newark: [-74.17, 40.69],
  savannah: [-81.09, 32.08],
  houston: [-95.27, 29.73],
  losAngeles: [-118.26, 33.73],
};
const POTI = [41.67, 42.15];

const projection = geoOrthographic().scale(R).translate([CX, CY]).rotate(ROTATION).clipAngle(90);
// Integer precision is invisible at this size and keeps the paths small.
const path = geoPath(projection).digits(0);

const point = (c, altitude = 0) => {
  const [x, y] = projection(c);
  return { x: +(CX + (x - CX) * (1 + altitude)).toFixed(1), y: +(CY + (y - CY) * (1 + altitude)).toFixed(1) };
};

const arc = (from) => {
  const interpolate = geoInterpolate(from, POTI);
  let d = "";
  for (let i = 0; i <= SAMPLES; i++) {
    const p = point(interpolate(i / SAMPLES), ARC_HEIGHT * Math.sin((Math.PI * i) / SAMPLES));
    d += `${i ? "L" : "M"}${p.x} ${p.y}`;
  }
  return d;
};

/** Drops points identical to the previous one (common after rounding). */
const dedupe = (d) => {
  let prev = "";
  return d.replace(/([MLZ])([^MLZ]*)/g, (m, cmd, xy) => {
    if (cmd === "L" && xy === prev) return "";
    if (cmd !== "Z") prev = xy;
    return m;
  });
};

const land = dedupe(path(feature(topology, topology.objects.land)));
const graticule = dedupe(path(geoGraticule10()));

const VIEWBOX = "-104 12 644 500";

// 1) Static base map as an image file — fetched once, cached, drawn like a photo.
const base = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEWBOX}" width="644" height="500">
<defs>
<radialGradient id="s" cx="40%" cy="34%" r="72%"><stop offset="0" stop-color="#243A6B"/><stop offset=".55" stop-color="#152447"/><stop offset="1" stop-color="#0A1430"/></radialGradient>
<radialGradient id="a" cx="50%" cy="50%" r="50%"><stop offset=".84" stop-color="#3A7DD8" stop-opacity=".45"/><stop offset=".92" stop-color="#3A7DD8" stop-opacity=".12"/><stop offset="1" stop-color="#3A7DD8" stop-opacity="0"/></radialGradient>
<radialGradient id="h" cx="34%" cy="26%" r="45%"><stop offset="0" stop-color="#fff" stop-opacity=".16"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>
</defs>
<circle cx="${CX}" cy="${CY}" r="${R + 34}" fill="url(#a)"/>
<circle cx="${CX}" cy="${CY}" r="${R}" fill="url(#s)"/>
<path d="${graticule}" fill="none" stroke="rgb(236,232,224)" stroke-opacity=".07" stroke-width=".75"/>
<path d="${land}" fill="rgb(236,232,224)" fill-opacity=".17" stroke="rgb(236,232,224)" stroke-opacity=".28" stroke-width=".6"/>
<circle cx="${CX}" cy="${CY}" r="${R}" fill="url(#h)" stroke="rgb(197,168,128)" stroke-opacity=".35"/>
</svg>
`;
writeFileSync(new URL("../public/globe-base.svg", import.meta.url), base);

// 2) The small, animated part (routes and points) for the component.
const out = `// GENERATED by scripts/build-globe.mjs — do not edit by hand.
// The base map itself is public/globe-base.svg.

export const GLOBE = { r: ${R}, cx: ${CX}, cy: ${CY}, viewBox: "${VIEWBOX}", width: 644, height: 500 } as const;

export const PORT_POINTS = ${JSON.stringify(Object.fromEntries(Object.entries(PORTS).map(([k, c]) => [k, point(c)])))} as const;

export const POTI_POINT = ${JSON.stringify(point(POTI))} as const;

/** Great-circle arcs, lifted off the surface, from each port to Poti. */
export const ROUTE_PATHS = ${JSON.stringify(Object.fromEntries(Object.entries(PORTS).map(([k, c]) => [k, arc(c)])))} as const;
`;

writeFileSync(new URL("../src/components/landing/globe-geometry.ts", import.meta.url), out);
console.log(`globe-base.svg ${(base.length / 1024).toFixed(1)} KB, globe-geometry.ts ${(out.length / 1024).toFixed(1)} KB`);
